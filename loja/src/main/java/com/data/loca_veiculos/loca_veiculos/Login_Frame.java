    private void jBtnacessarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnacessarActionPerformed
    String url = "jdbc:mysql://127.0.0.1:3306/PeixariaA3?useSSL=false&serverTimezone=UTC";
        String usuarioDb = "root"; 
        String senhaDb = "123456"; 
        
        // 1. Pega e valida o e-mail digitado
        String emailDigitado = jTxtusuario.getText().trim();
        if (emailDigitado.isEmpty()) {
            JOptionPane.showMessageDialog(null, "O e-mail do usuário é obrigatório!");
            return; 
        }
        
        // 2. Pega e valida a senha digitada
        String senhaDigitada = new String(jTxtsenha.getPassword()).trim();
        if (senhaDigitada.isEmpty()) {
            JOptionPane.showMessageDialog(null, "A senha do usuário é obrigatória!");
            return; 
        }
        
        // 3. Consulta ajustada para a tabela 'pescadores' do banco PeixariaA3
        String sql = "SELECT * FROM pescadores WHERE email = ? AND senha_hash = ?";

        try (Connection conexao = DriverManager.getConnection(url, usuarioDb, senhaDb);
             PreparedStatement stmt = conexao.prepareStatement(sql)) {
            
            stmt.setString(1, emailDigitado);
            stmt.setString(2, senhaDigitada);
            
            try (ResultSet rslogin = stmt.executeQuery()) {
                if (rslogin.next()) { 
                    String nomePescador = rslogin.getString("nome");
                    JOptionPane.showMessageDialog(null, "Bem-vindo, " + nomePescador + "!");
                    
                    Menu_Frame menu = new Menu_Frame();
                    menu.setVisible(true);
                    this.dispose(); // Fecha a tela de login
                } else {
                    JOptionPane.showMessageDialog(null, "E-mail ou senha inválidos.");
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Erro ao conectar ao banco de dados: " + e.getMessage());
            System.err.println("Erro SQL: " + e.getMessage());
        }
    }//GEN-LAST:event_jBtnacessarActionPerformed

